"""Regenerate pure #1513 editor bounds/bases/fingerprints; no client artwork."""
from pathlib import Path
import hashlib
import ast
import json
import pprint
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src/res/scripts/client'))
from gui.mods.offline_lan_0922.ai.maps import TACTICAL_MAPS


def build():
    entries = {}
    for path in sorted((ROOT / 'navgraphs').glob('*.json')):
        if path.name == 'manifest.json':
            continue
        raw = path.read_bytes()
        graph = json.loads(raw)
        if 'map' not in graph:
            continue
        name = graph['map']
        entries[name] = dict(bounds=list(TACTICAL_MAPS[name]['bounds']),
                             bases=graph['bases'],
                             route_ids=dict((team, [r['id'] for r in routes])
                                            for team, routes in graph['routes'].items()),
                             resource_sha256=hashlib.sha256(raw).hexdigest())
        if graph.get('capture_coordinate_previous_sha256'):
            entries[name]['capture_coordinate_previous_sha256'] = graph['capture_coordinate_previous_sha256']
        if graph.get('route_previous_sha256'):
            entries[name]['route_previous_sha256'] = graph['route_previous_sha256']
        if graph.get('terrain_edge_previous_sha256'):
            entries[name]['terrain_edge_previous_sha256'] = graph['terrain_edge_previous_sha256']
        if graph.get('navigation_previous_sha256'):
            entries[name]['navigation_previous_sha256'] = graph['navigation_previous_sha256']
    if len(entries) != 41:
        raise RuntimeError('Expected the pinned 41-map registry')
    return entries


if __name__ == '__main__':
    path = ROOT / 'src/res/scripts/client/gui/mods/offline_lan_0922/bot_editor_maps.py'
    header = ('# -*- coding: utf-8 -*-\n'
              '"""Exact #1513 authoring bounds, bases and baked resource identity.\n'
              'Generated by tools/build_bot_editor_maps.py; no client artwork.\n"""\n')
    entries = build()
    path.write_text(header + 'MAPS = ' + pprint.pformat(entries, sort_dicts=True) + '\n', encoding='utf8')
    # First-run/reset tactics must carry current graph identities too. Retain
    # the reviewed geometry and original source provenance verbatim.
    defaults = path.with_name('bot_tactics_default_data.py')
    source = defaults.read_text(encoding='utf8')
    tree = ast.parse(source)
    assignment = next(node for node in tree.body if isinstance(node, ast.Assign)
                      and any(isinstance(t, ast.Name) and t.id == 'PROFILE_JSON'
                              for t in node.targets))
    profile = json.loads(ast.literal_eval(assignment.value))
    for name, entry in profile['maps'].items():
        entry['resource_sha256'] = entries[name]['resource_sha256']
    payload = json.dumps(profile, sort_keys=True, separators=(',', ':'), ensure_ascii=True)
    lines = source.splitlines(True)
    lines[assignment.lineno-1:assignment.end_lineno] = ['PROFILE_JSON = %r\n' % payload]
    defaults.write_text(''.join(lines), encoding='utf8')
