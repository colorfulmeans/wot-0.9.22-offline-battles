"""Export exact #1513 BWWa water rectangles, independently of render visibility."""
import argparse
import io
import json
import math
from pathlib import Path
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'tools'))
import bake_navigation_0922 as baker


def build(client):
    sys.path.insert(0, baker.VENDOR_ROOT)
    from wot_space_bin_utils import CompiledSpace
    maps = {}
    for path in sorted((ROOT/'navgraphs').glob('*.json')):
        graph = json.loads(path.read_bytes())
        name = graph.get('map')
        if name is None:
            continue
        with zipfile.ZipFile(Path(client)/'res/packages'/str(name+'.pkg')) as package:
            compiled = CompiledSpace(io.BytesIO(package.read('spaces/%s/space.bin' % name)),
                                     '0.9.22.0.1', 'RU', ['BWWa'])
        rows = []
        for water in compiled.sections['BWWa']._data['1']:
            x, y, z = water['position']
            width, length = water['size']
            yaw = water['orientation']
            row = (x, y, z, width/2., length/2., math.cos(yaw), math.sin(yaw))
            assert all(math.isfinite(v) for v in row) and width > 0 and length > 0
            rows.append(row)
        maps[name] = rows
    destination = ROOT/'src/res/scripts/client/gui/mods/offline_lan_0922/water_surface_data.py'
    payload = json.dumps(maps, sort_keys=True, separators=(',', ':'))
    destination.write_bytes(('"""Generated by tools/build_water_surfaces_0922.py from #1513 BWWa.\n'
        'Rectangles are collision surfaces, not BWWa streaming cells or navigation hazards.\n"""\n'
        'import json\n\nSURFACES = json.loads(%r)\n' % payload).encode('ascii'))
    print('Exported %d maps, %d water rectangles' % (len(maps), sum(map(len, maps.values()))))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--client', required=True)
    build(parser.parse_args().client)
